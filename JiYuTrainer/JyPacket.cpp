const unsigned char* BasePacket(Kind kind) {
    int index = static_cast<int>(kind);
    if (index < 0 || index >= 4) return nullptr;
    return kBasePack[index];
}

int PayloadOffset(Kind kind) {
    switch (kind) {
    case Kind::Message: return 56;
    case Kind::Command: return 100;
    default: return -1;
    }
}

int MaxPayloadChars(Kind kind) {
    int offset = PayloadOffset(kind);
    if (offset < 0) return 0;
    return (kSendBufferSize - offset) / static_cast<int>(sizeof(wchar_t));
}

void Build(Kind kind, const std::wstring& payload, unsigned char* out, size_t outSize) {
    if (!out || outSize == 0) return;

    static_assert(sizeof(wchar_t) == 2, "JiYu protocol requires UTF-16 wchar_t");

    const size_t bytes = (std::min)(outSize, static_cast<size_t>(kSendBufferSize));
    std::memset(out, 0, bytes);

    const unsigned char* base = BasePacket(kind);
    if (!base) return;
    std::memcpy(out, base, (std::min)(bytes, static_cast<size_t>(kBasePacketSize)));

    const int offset = PayloadOffset(kind);
    if (offset < 0 || payload.empty() || static_cast<size_t>(offset) >= bytes) return;

    const size_t maxChars = (bytes - static_cast<size_t>(offset)) / sizeof(wchar_t);
    const size_t chars = (std::min)(payload.size(), maxChars);
    if (chars > 0)
        std::memcpy(out + offset, payload.data(), chars * sizeof(wchar_t));
}

